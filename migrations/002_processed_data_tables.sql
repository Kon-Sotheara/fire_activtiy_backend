alter table fire_events add column if not exists event_id varchar(40);
alter table fire_events add column if not exists grid_id varchar(30);
alter table fire_events add column if not exists week date;

create unique index if not exists fire_events_event_id_idx on fire_events (event_id);
create index if not exists fire_events_grid_id_idx on fire_events (grid_id);
create index if not exists fire_events_week_idx on fire_events (week);

create table if not exists weekly_grid (
    id bigint generated by default as identity primary key,
    week date not null,
    grid_id varchar(30) not null,
    modis_count integer not null default 0,
    modis_frp_sum double precision not null default 0,
    viirs_count integer not null default 0,
    viirs_frp_sum double precision not null default 0,
    unique_fire_events integer not null default 0,
    unique (week, grid_id)
);

create index if not exists weekly_grid_week_idx on weekly_grid (week);
create index if not exists weekly_grid_grid_id_idx on weekly_grid (grid_id);
