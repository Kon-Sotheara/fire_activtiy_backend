create table if not exists fire_events (
    id bigint generated by default as identity primary key,
    acq_date date not null,
    latitude double precision not null,
    longitude double precision not null,
    detection_count integer not null,
    modis_detections integer not null default 0,
    viirs_detections integer not null default 0,
    source_sensors varchar(20) not null,
    fire_type integer,
    total_frp double precision,
    confidence_score double precision,
    daynight varchar(5),
    sensor_agreement varchar(20) not null default 'unknown'
);

alter table fire_events add column if not exists confidence_score double precision;
alter table fire_events add column if not exists daynight varchar(5);
alter table fire_events add column if not exists sensor_agreement varchar(20) not null default 'unknown';

create index if not exists fire_events_acq_date_idx on fire_events (acq_date);
create index if not exists fire_events_fire_type_idx on fire_events (fire_type);
